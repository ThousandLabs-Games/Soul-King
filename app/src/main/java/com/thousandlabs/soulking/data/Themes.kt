/**
 * Morceau précis choisi à la main : vérifié avant d'entrer dans la partie.
 * [alts] : autres façons d'écrire le titre. [loose] : génériques, reconnus par le nom de l'émission.
 */
data class Curated(
    val title: String,
    val artist: String = "",
    val anime: String? = null,
    val alts: List<String> = emptyList(),
    val query: String? = null,
    val loose: Boolean = false,
    /** Le résultat doit être présenté comme un générique (« Générique », « Theme »…). */
    val needsMarker: Boolean = false,
    /** Générique sans paroles à l'origine : une version instrumentale est la bonne. */
    val instrumentalOk: Boolean = false,
)

private fun Curated.instrumental() = copy(instrumentalOk = true)

/** Générique de dessin animé, recherché en version française par le nom de l'émission. */
private fun cartoon(show: String, vararg alts: String) =
    Curated(title = show, anime = show, alts = alts.toList(), query = "générique $show", loose = true, needsMarker = true)

/** Générique dont la version originale est celle que tout le monde connaît. */
private fun cartoonOriginal(show: String, query: String, vararg alts: String) =
    Curated(title = show, anime = show, alts = alts.toList(), query = query, loose = true)

data class ThemeDef(
    val id: String,
    val title: String,
    val subtitle: String,
    val icon: ImageVector,
    /** Les morceaux les plus connus de chacun de ces artistes. */
    val artists: List<String> = emptyList(),
    /** Recherches de playlists publiques. */
    val playlists: List<String> = emptyList(),
    /** Morceaux précis. */
    val curated: List<Curated> = emptyList(),
    /** Tous les morceaux du thème appartiennent à cet animé. */
    val forceAnime: String? = null,
    /** Morceaux du téléphone qui vont avec : un animé précis… */
    val localAnime: String? = null,
    /** … ou tous les openings du téléphone. */
    val localAnyAnime: Boolean = false,
    /** Mot affiché dans la question : « Trouvez le dessin animé ». */
    val whoWord: String? = null,
    /** On devine uniquement l'émission ou l'animé, pas le titre. */
    val whoOnly: Boolean = false,
)

